-- | Розбір сирого тексту на абзаци, речення, слова та розділові знаки.
-- Під час розбору табуляції й послідовності пробілів замінюються одним пробілом.
module TextParser
  ( розібратиТекст
  , зібратиТекст
  ) where

import Data.Char (isDigit, isSpace)
import Data.List (intercalate)

import TextTypes

-- | Проміжний токен, який використовується лише під час розбору рядка.
data Токен
  = ТСлово Слово
  | ТЗнак РозділовийЗнак
  | ТПробіл
  deriving (Eq, Show)

-- | Розібрати рядок файлу в структуру Текст.
розібратиТекст :: String -> Текст
розібратиТекст =
  Текст
    . map (Абзац . concatMap реченняЗРядка)
    . абзаци
    . map нормалізуватиРядок
    . lines
    . filter (/= '\r')

-- | Зібрати структуру Текст назад у рядок для виведення.
-- Між словами завжди один пробіл, абзаци відділені порожнім рядком.
зібратиТекст :: Текст -> String
зібратиТекст (Текст абзаци') =
  intercalate "\n\n" (map зібратиАбзац абзаци') ++ "\n"
  where
    зібратиАбзац (Абзац речення) =
      unwords (filter (not . null) (map зібратиРечення речення))

-- | Заміна табуляцій і послідовностей пробілів одним пробілом.
-- Функція words розбиває рядок за будь-якими пробільними символами,
-- а unwords з'єднує отримані слова рівно одним пробілом.
нормалізуватиРядок :: String -> String
нормалізуватиРядок = unwords . words

-- | Об'єднати непорожні рядки в абзаци; порожні рядки є межею абзацу.
абзаци :: [String] -> [[String]]
абзаци [] = []
абзаци (r:rs)
  | null r = абзаци rs
  | otherwise =
      let (блок, решта) = span (not . null) (r:rs)
      in блок : абзаци решта

-- | Розбити один рядок на речення.
реченняЗРядка :: String -> [Пропозиція]
реченняЗРядка = скластиРечення . з'єднатиДесяткові . токенізувати

-- | Перетворити нормалізований рядок у список токенів.
токенізувати :: String -> [Токен]
токенізувати [] = []
токенізувати s@(c:cs)
  | c == ' ' = ТПробіл : токенізувати cs
  | take 3 s == "..." = ТЗнак ТриКрапки : токенізувати (drop 3 s)
  | otherwise =
      case знакЗаСимволом c of
        Just z  -> ТЗнак z : токенізувати cs
        Nothing ->
          let (w, решта) = span єСимволомСлова s
          in if null w
               then токенізувати cs -- страховка від зациклення
               else ТСлово w : токенізувати решта

-- | Символи, які можуть входити до складу слова.
-- Усі символи, крім пробілів і розділових знаків, вважаємо частиною слова:
-- це дає змогу зберегти як "з'єднання", так і оператори типу (+1) чи ->.
єСимволомСлова :: Символ -> Bool
єСимволомСлова c = not (isSpace c) && знакЗаСимволом c == Nothing

-- | Відповідність між символом і розділовим знаком.
знакЗаСимволом :: Символ -> Maybe РозділовийЗнак
знакЗаСимволом c = case c of
  '.'  -> Just Крапка
  ','  -> Just Кома
  ';'  -> Just КрапкаКома
  ':'  -> Just Двокрапка
  '?'  -> Just ЗнакПитань
  '!'  -> Just ЗнакОкличу
  '('  -> Just КруглаДужкаВідкрита
  ')'  -> Just КруглаДужкаЗакрита
  '['  -> Just КвадратнаДужкаВідкрита
  ']'  -> Just КвадратнаДужкаЗакрита
  '-'  -> Just Дефіс
  _    -> Nothing

-- | Не робити речення з десяткового числа на кшталт 3.14.
з'єднатиДесяткові :: [Токен] -> [Токен]
з'єднатиДесяткові (ТСлово (aA@(_:_)) : ТЗнак Крапка : ТСлово (bB@(b:_)) : решта)
  | isDigit (last aA) && isDigit b =
      з'єднатиДесяткові (ТСлово (aA ++ "." ++ bB) : решта)
з'єднатиДесяткові (t:ts) = t : з'єднатиДесяткові ts
з'єднатиДесяткові [] = []

-- | Зібрати токени в речення. Знак кінця речення закриває поточне речення.
скластиРечення :: [Токен] -> [Пропозиція]
скластиРечення = завершити . foldl крок ([], [])
  where
    крок (готові, поточне) tok = case tok of
      ТПробіл -> (готові, поточне ++ [Пробіл])
      ТСлово w -> (готові, поточне ++ [Слівце w])
      ТЗнак z ->
        let поточне' = поточне ++ [Знак z]
        in if єЗнакомРечення z
             then (готові ++ [Пропозиція поточне'], [])
             else (готові, поточне')

    завершити (готові, поточне) =
      готові ++ [Пропозиція поточне | not (null поточне)]

-- | Вивести одне речення: знаки прилягають до слів згідно з початковим
-- розташуванням, а будь-які послідовності пробілів стискаються до одного
-- (words/unwords також прибирають пробіли на початку й у кінці речення).
зібратиРечення :: Пропозиція -> String
зібратиРечення (Пропозиція елементи) =
  unwords . words . concatMap текстЕлемента $ елементи
  where
    текстЕлемента (Слівце w) = w
    текстЕлемента (Знак z)   = символЗнака z
    текстЕлемента Пробіл     = " "
