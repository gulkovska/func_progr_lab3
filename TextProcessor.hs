-- | Обробка тексту: видалення слів заданої довжини,
-- які починаються з приголосної літери.
module TextProcessor
  ( видалитиСловаЗаДовжиною
  ) where

import TextTypes

-- | Видалити з тексту всі слова заданої довжини,
-- що починаються з приголосної літери.
видалитиСловаЗаДовжиною :: Int -> Текст -> Текст
видалитиСловаЗаДовжиною n (Текст абзаци') =
  Текст (map обробитиАбзац абзаци')
  where
    обробитиАбзац (Абзац речення) = Абзац (map обробитиРечення речення)

    обробитиРечення (Пропозиція елементи) =
      Пропозиція (filter требаЗалишити елементи)

    требаЗалишити (Слівце w) =
      not (length w == n && починаєтьсяЗПриголосної w)
    требаЗалишити _ = True
