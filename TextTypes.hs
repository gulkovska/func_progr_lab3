-- | Типи для подання тексту підручника з програмування.
-- Назви типів подано українською мовою згідно з умовою завдання.
module TextTypes
  ( Символ
  , Слово
  , РозділовийЗнак(..)
  , ЕлементПропозиції(..)
  , Пропозиція(..)
  , Абзац(..)
  , Текст(..)
  , єЗнакомРечення
  , символЗнака
  , голосні
  , приголосні
  , починаєтьсяЗПриголосної
  ) where

import Data.Char (toLower)

-- | Один символ тексту (літера, цифра тощо).
type Символ = Char

-- | Слово як послідовність символів.
type Слово = [Символ]

-- | Розділові знаки, які можна зустріти в підручнику.
data РозділовийЗнак
  = Крапка
  | Кома
  | КрапкаКома
  | Двокрапка
  | ЗнакПитань
  | ЗнакОкличу
  | ТриКрапки
  | КруглаДужкаВідкрита
  | КруглаДужкаЗакрита
  | КвадратнаДужкаВідкрита
  | КвадратнаДужкаЗакрита
  | Дефіс
  deriving (Eq, Ord, Show, Enum, Bounded)

-- | Елемент речення: або слово, або розділовий знак.
data ЕлементПропозиції
  = Слівце Слово
  | Знак РозділовийЗнак
  | Пробіл
  deriving (Eq, Show)

-- | Пропозиція (речення) як послідовність слів і розділових знаків.
newtype Пропозиція = Пропозиція [ЕлементПропозиції]
  deriving (Eq, Show)

-- | Абзац як послідовність речень.
newtype Абзац = Абзац [Пропозиція]
  deriving (Eq, Show)

-- | Весь текст як послідовність абзаців.
newtype Текст = Текст [Абзац]
  deriving (Eq, Show)

-- | Чи завершує цей знак речення.
єЗнакомРечення :: РозділовийЗнак -> Bool
єЗнакомРечення z = z `elem` [Крапка, КрапкаКома, ЗнакПитань, ЗнакОкличу, ТриКрапки]

-- | Текстове подання розділового знака.
символЗнака :: РозділовийЗнак -> String
символЗнака z = case z of
  Крапка                   -> "."
  Кома                     -> ","
  КрапкаКома               -> ";"
  Двокрапка                -> ":"
  ЗнакПитань               -> "?"
  ЗнакОкличу               -> "!"
  ТриКрапки                -> "..."
  КруглаДужкаВідкрита      -> "("
  КруглаДужкаЗакрита       -> ")"
  КвадратнаДужкаВідкрита   -> "["
  КвадратнаДужкаЗакрита    -> "]"
  Дефіс                    -> "-"

-- | Голосні літери української та латинської абеток.
голосні :: String
голосні = "аеєиіїоууюяАЕЄИІЇОУЮЯaeiouyAEIOUY"

-- | Приголосні літери української та латинської абеток.
приголосні :: String
приголосні = "бвгґджзйклмнпрстфхцчшщьБВГҐДЖЗЙКЛМНПРСТФХЦЧШЩЬbcdfghjklmnpqrstvwxyzBCDFGHJKLMNPQRSTVWXYZ"

-- | Перевірка: слово починається з приголосної літери.
-- Слова, що починаються з цифри або розділового знака, не видаляються.
починаєтьсяЗПриголосної :: Слово -> Bool
починаєтьсяЗПриголосної (c:_) = toLower c `elem` приголосні
починаєтьсяЗПриголосної []    = False
